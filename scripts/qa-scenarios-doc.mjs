#!/usr/bin/env node
// Prints the QA user scenarios document (brief: qa-scenarios) from server/qa/scenarios.ts, the list the picker's "Used in" tags and the accounts
// document also read, so the three cannot drift.
//   npx tsx scripts/qa-scenarios-doc.mjs --write "<project docs>/ops/qa-scenarios.md"   regenerates the page in place and keeps the Results written by hand (and its properties block)
//   npx tsx scripts/qa-scenarios-doc.mjs --from "<page>"   prints the same to the screen (never redirect with > to the page itself: the shell empties it before it is read)
//   npx tsx scripts/qa-scenarios-doc.mjs   prints a page with every Result blank
//   npx tsx scripts/qa-scenarios-doc.mjs --check "<project docs>/ops/qa-scenarios.md"   exits 1 when the page lacks a live scenario, lists one that no longer exists, or shows a retired one as live (Results filled in by hand are not compared; a changed title, account, step or expected line is)
// The Result column is blank on a new page on purpose: the owner fills it by hand (date, pass or fail, note) while walking the scenarios on QA. A
// regenerated page carries each non-empty Result forward by scenario id (from the Summary table, and from a hand-filled line under the scenario).
import { existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { personaById, personaEmail } from '../server/qa/personas.ts';
import { SCENARIO_FEATURES, SCENARIOS } from '../server/qa/scenarios.ts';

const PLACEHOLDER = '\\_\\_\\_';
const splitRow = line => line.replace(/^\|\s*|\s*\|\s*$/g, '').split(/(?<!\\)\|/).map(c => c.trim());

/** The hand-written Results on a page, keyed by scenario id: the Summary table's Result cell, else the line under the scenario when it is filled in. */
export function resultsOf(doc) {
  const out = new Map();
  for (const m of doc.matchAll(/^- \*\*Result\*\* \(date, pass or fail, note\): (.*)$/gm)) {
    const id = [...doc.slice(0, m.index).matchAll(/^### (S-\d+)\. /gm)].at(-1)?.[1];
    if (id && m[1].trim() && m[1].trim() !== PLACEHOLDER) out.set(id, { line: m[1].trim() });
  }
  const summary = doc.split(/^## Summary$/m)[1] ?? '';
  for (const row of summary.split('\n').filter(l => /^\| S-\d+ \|/.test(l))) {
    const cells = splitRow(row);
    const note = cells.slice(4).join('\\|'); // an unescaped | inside the note stays part of it
    if (cells.length >= 5 && note) out.set(cells[0], { ...out.get(cells[0]), cell: note });
  }
  return out;
}

const FRONT = today => `---
dg-publish: false
tags:
author:
banner:
banner_x:
banner_y:
cssclasses:
Comments:
Purpose: Numbered user scenarios to walk on QA, each tied to a test account, with a Result column to fill by hand
Status: current (${today}, generated); no scenario has been run
Started: ${today}
EditDate: ${today}
Relates: "[[briefs/qa-scenarios]], [[qa-test-accounts]], [[briefs/qa-picker-access]]"
---`;

/** The properties block: the existing page's own (kept as it is, with EditDate set to today), or a new one. */
function frontOf(existing, today) {
  const m = existing.match(/^---\n[\s\S]*?\n---(?=\n)/);
  if (!m) return FRONT(today);
  return /^EditDate:.*$/m.test(m[0]) ? m[0].replace(/^EditDate:.*$/m, `EditDate: ${today}`) : m[0];
}

/** The page as text, for the test and for printing. Built on demand, so importing this file (or running --check) does no work. `existing` is the page being replaced: its Results and properties block carry over. */
export function buildDoc(existing = '') {
  const out = [];
  const today = new Date().toISOString().slice(0, 10);
  const kept = resultsOf(existing);
  const live = SCENARIOS.filter(s => !s.retired);
  const devices = live.filter(s => s.device).length;
  const cell = t => t.replaceAll('|', '\\|');

  out.push(`${frontOf(existing, today)}
# QA user scenarios

> Generated by \`npx tsx scripts/qa-scenarios-doc.mjs\` from \`server/qa/scenarios.ts\`. Edit the list there, then regenerate this page with \`--write\` (and \`qa-test-accounts.md\`); your Results are kept. The Result column is yours: write the date, pass or fail and a note. Nothing in the app records a result.

${live.length} scenarios across ${SCENARIO_FEATURES.length} features. ${devices} need a real phone (marked **device**). Each runs as one test account: open the picker (account menu, **QA test accounts**), search the scenario id (for example \`S-04\`), press **Switch**, or open \`https://qa.loadbearer.app/?qa=<account id>\` as an admin to land on that account in the picker. If the account is not seeded, press **Seed** in the picker first; **Reset** puts an account back to its starting data after a scenario changed it.

**Press Reset on the account before you start.** The seed writes its foods, plans and logs with dates counted from the day the account was seeded, so an account seeded days ago shows an empty "today". Reset is greyed on the account you are on: switch to another account first, then Reset the one you want, then switch back.

Steps are written from each shipped brief's Done when lines and the feature map. If the app does something else, record the difference in Result: the scenario text is a script, not proof the feature works.
`);
  for (const feature of SCENARIO_FEATURES) {
    const rows = SCENARIOS.filter(s => s.feature === feature);
    if (!rows.length) continue;
    out.push(`## ${feature}\n`);
    for (const s of rows) {
      const p = personaById(s.persona);
      out.push(`### ${s.id}. ${s.title}${s.retired ? ' (retired)' : ''}`);
      out.push(`- **Account:** ${p ? `${p.name} (\`${p.id}\`, ${personaEmail(p.id)}); open it with \`/?qa=${p.id}\`` : `\`${s.persona}\``}`);
      out.push(`- **Kind:** ${s.edge ? 'edge case' : 'happy path'}${s.device ? '; **device** (needs a real phone)' : ''}`);
      out.push(`- **From:** ${s.brief === 'feature-map' ? 'the feature map (no brief)' : `[[briefs/${s.brief}]]`}`);
      out.push('- **Steps:**');
      s.steps.forEach((t, i) => out.push(`  ${i + 1}. ${t}`));
      out.push('- **Expected:**');
      s.expected.forEach(t => out.push(`  - ${t}`));
      out.push(`- **Result** (date, pass or fail, note): ${kept.get(s.id)?.line ?? PLACEHOLDER}\n`);
    }
  }
  out.push('## Summary\n\n| Id | Feature | Account | Device | Result |\n|---|---|---|---|---|');
  for (const s of SCENARIOS) out.push(`| ${s.id} | ${cell(s.feature)} | \`${s.persona}\` | ${s.device ? 'yes' : ''} | ${kept.get(s.id)?.cell ?? ''} |`);
  return out.join('\n') + '\n';
}


/** Each scenario's text on a page, keyed by id: from its `### S-nn.` heading up to its Result line, so the Results written by hand are not part of it. */
const blocksOf = doc => new Map([...doc.matchAll(/^### (S-\d+)\. [\s\S]*?(?=^- \*\*Result\*\*)/gm)].map(m => [m[1], m[0]]));

/** What is out of step between a scenarios page and the list: ids missing from the page, ids on it that no longer exist, a retired one shown as live (or the reverse), and a scenario whose title, account, steps or expected lines differ. Results written by hand are not compared. */
export function docIssues(doc) {
  const onPage = new Map([...doc.matchAll(/^### (S-\d+)\. .*?( \(retired\))?$/gm)].map(m => [m[1], Boolean(m[2])]));
  const fresh = blocksOf(buildDoc());
  const page = blocksOf(doc);
  const issues = [];
  for (const s of SCENARIOS) {
    if (!onPage.has(s.id)) issues.push(`${s.id} is not on the page`);
    else if (onPage.get(s.id) !== Boolean(s.retired)) issues.push(`${s.id} is ${s.retired ? 'retired' : 'live'} in the list but ${s.retired ? 'live' : 'retired'} on the page`);
    else if (page.get(s.id) !== fresh.get(s.id)) issues.push(`${s.id} reads differently on the page than in the list (title, account, steps or expected lines changed)`);
  }
  for (const id of onPage.keys()) if (!SCENARIOS.some(s => s.id === id)) issues.push(`${id} is on the page but not in the list`);
  return issues;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const at = process.argv.indexOf('--check');
  const arg = name => { const i = process.argv.indexOf(name); return i < 0 ? null : (process.argv[i + 1] ?? ''); };
  const target = arg('--write') ?? arg('--from');
  if (target === '') { console.error('usage: qa-scenarios-doc.mjs [--write|--from "<path of the scenarios page>"]'); process.exit(2); }
  if (target && !existsSync(target)) { console.error(`qa-scenarios: ${target} does not exist. Run without --write or --from to print a new page.`); process.exit(2); }
  if (at < 0) {
    const text = buildDoc(target ? readFileSync(target, 'utf8') : '');
    if (!target) console.error('qa-scenarios: no page given, so every Result is blank. Use --write "<page>" to regenerate a page and keep its Results.');
    if (arg('--write')) { writeFileSync(`${target}.tmp`, text); renameSync(`${target}.tmp`, target); console.error(`qa-scenarios: wrote ${target}.`); }
    else process.stdout.write(text);
  } else {
    if (!process.argv[at + 1]) { console.error('usage: qa-scenarios-doc.mjs --check "<path of the scenarios page>"'); process.exit(2); }
    const issues = docIssues(readFileSync(process.argv[at + 1], 'utf8'));
    for (const i of issues) console.error(`qa-scenarios: ${i}`);
    if (issues.length) { console.error('Regenerate the page with --write "<page>"; the Result column is kept.'); process.exit(1); }
    console.error('qa-scenarios: the page matches the list.');
  }
}
